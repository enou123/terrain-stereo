export function matchingLandmark(location){return LANDMARKS.find(p=>Math.abs(p.center.latitude-location.latitude)<.0001&&Math.abs(p.center.longitude-location.longitude)<.0001)||null;}
export function filterLandmarks(category='',region=''){return LANDMARKS.filter(p=>(!category||p.categories.includes(category))&&(!region||p.region===region));}
